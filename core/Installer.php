<?php
namespace Core;

/** Web installer. Active only until storage/installed.lock exists. */
final class Installer {
  public static function routes(Router $r): void {
    $o = ['auth' => false];
    $r->get('/install', [self::class, 'requirementsPage'], $o);
    $r->post('/install/database', [self::class, 'database'], $o + ['throttle' => [20, 600]]);
    $r->get('/install/setup', [self::class, 'setupPage'], $o);
    $r->post('/install/run', [self::class, 'run'], $o + ['throttle' => [10, 600]]);
    $r->get('/{any}', static fn () => Response::redirect(url('/install')), $o);
    $r->get('/', static fn () => Response::redirect(url('/install')), $o); }

  public function __construct(private Request $req) {}

  public static function requirements(): array {
    $w = static fn (string $d) => is_dir(NY_ROOT.'/'.$d) && is_writable(NY_ROOT.'/'.$d);
    return [
      ['PHP '.NY_MIN_PHP.'+ (current '.PHP_VERSION.')', version_compare(PHP_VERSION, NY_MIN_PHP, '>='), true],
      ['PDO MySQL extension', extension_loaded('pdo_mysql'), true],
      ['mbstring extension', extension_loaded('mbstring'), true],
      ['OpenSSL extension', extension_loaded('openssl'), true],
      ['Sodium extension (encryption)', extension_loaded('sodium'), true],
      ['Fileinfo extension (upload checks)', extension_loaded('fileinfo'), true],
      ['JSON extension', extension_loaded('json'), true],
      ['cURL extension (AI, updates)', extension_loaded('curl'), false],
      ['Zip extension (backups, updates)', class_exists('ZipArchive'), false],
      ['Zlib extension (PDF, backups)', extension_loaded('zlib'), true],
      ['iconv extension (PDF text)', extension_loaded('iconv'), true],
      ['config/ writable', $w('config'), true],
      ['storage/ writable', $w('storage'), true],
      ['assets/uploads/ writable', $w('assets/uploads'), true]]; }

  private function guard(): void { if (App::installed()) { throw new HttpException(404, 'Already installed.'); } }

  public function requirementsPage(): Response {
    $this->guard();
    $reqs = self::requirements();
    $ok = !array_filter($reqs, static fn ($r) => $r[2] && !$r[1]);
    return Response::view('install/requirements', ['title' => 'Install', 'reqs' => $reqs, 'ok' => $ok, 'db' => Session::get('install_db', [])], 'layouts/blank'); }

  public function database(): Response {
    $this->guard();
    $d = ['host' => $this->req->str('host', 'localhost'), 'port' => $this->req->int('port', 3306), 'name' => $this->req->str('name'), 'user' => $this->req->str('user'), 'pass' => (string) $this->req->input('pass', '')];
    try {
      $pdo = DB::connect($d);
      $v = (string) $pdo->query('SELECT VERSION()')->fetchColumn();
      if ($pdo->query('SHOW TABLES')->fetchColumn()) { throw new \RuntimeException('Database is not empty. Use an empty database to avoid overwriting data.'); }
      Session::put('install_db', $d);
      Session::flash('toast', ['type' => 'success', 'msg' => 'Connected to '.$v]);
      return Response::redirect(url('/install/setup')); }
    catch (\Throwable $e) {
      Session::put('install_db', ['pass' => ''] + $d);
      Session::flash('toast', ['type' => 'error', 'msg' => 'Database error: '.$e->getMessage()]);
      return Response::redirect(url('/install')); } }

  public function setupPage(): Response {
    $this->guard();
    if (!Session::get('install_db')) { return Response::redirect(url('/install')); }
    return Response::view('install/setup', ['title' => 'Install'], 'layouts/blank'); }

  public function run(): Response {
    $this->guard();
    $db = Session::get('install_db') ?? throw new HttpException(400, 'Database step missing.');
    $d = Validator::make($this->req->all(), ['app_name' => 'required|max:60', 'app_url' => 'required|url|max:190', 'timezone' => 'required|max:60', 'currency_symbol' => 'required|max:5', 'name' => 'required|max:150', 'email' => 'required|email|max:190', 'password' => 'required|confirmed']);
    if ($e = Auth::validatePassword((string) $d['password'])) { throw new ValidationException(['password' => $e]); }
    if (!in_array($d['timezone'], \DateTimeZone::listIdentifiers(), true)) { throw new ValidationException(['timezone' => 'Unknown timezone']); }
    $config = ['app_key' => Crypto::generateKey(), 'app_url' => rtrim($d['app_url'], '/'), 'debug' => false, 'timezone' => $d['timezone'], 'db' => $db, 'installed_at' => date('c')];
    $tmp = NY_ROOT.'/config/config.php';
    if (file_put_contents($tmp, "<?php\n// Generated by the Niyanta installer. Keep this file private.\nreturn ".var_export($config, true).";\n", LOCK_EX) === false) { throw new HttpException(500, 'Cannot write config/config.php'); }
    @chmod($tmp, 0640);
    App::setConfig($config);
    date_default_timezone_set($d['timezone']);
    DB::init($db);
    try {
      Migrator::ensureTable();
      Migrator::migrate();
      self::seed($d);
      file_put_contents(NY_ROOT.'/storage/installed.lock', date('c'));
      Cache::flush(); }
    catch (\Throwable $e) { @unlink($tmp); throw $e; }
    Session::forget('install_db');
    Session::flash('toast', ['type' => 'success', 'msg' => 'Niyanta is installed. Sign in with your Super Admin account.']);
    return Response::redirect(url('/login')); }

  /** Seed roles, default settings, modules, permissions and the first Super Admin. */
  public static function seed(array $d): int {
    $now = date('Y-m-d H:i:s');
    foreach ([['super_admin', 'Super Admin', 'Complete control of the system'], ['manager', 'Manager', 'Manages clients, projects, teams and approvals'], ['hr', 'HR', 'Manages employees, attendance, leave and payroll'], ['employee', 'Employee', 'Works on assigned projects and tasks']] as [$slug, $name, $desc]) {
      DB::query('INSERT IGNORE INTO roles (slug, name, description, is_system, created_at) VALUES (?,?,?,1,?)', [$slug, $name, $desc, $now]); }
    Modules::load();
    foreach (Modules::discover() as $k => $m) { DB::query('INSERT IGNORE INTO modules (`key`, enabled, updated_at) VALUES (?,?,?)', [$k, empty($m['labs']) ? 1 : 0, $now]); }
    Modules::syncPermissions();
    Settings::setMany(['branding.app_name' => $d['app_name'], 'branding.tagline' => 'Run your agency with ease', 'general.timezone' => $d['timezone'], 'general.currency_symbol' => $d['currency_symbol'], 'general.currency_code' => 'INR', 'general.date_format' => 'd M Y', 'general.time_format' => 'h:i A', 'general.week_start' => '1', 'general.weekend_days' => '6,7',
      'appearance.default_theme' => 'system', 'appearance.font_family' => 'Plus Jakarta Sans', 'security.session_idle_minutes' => '120', 'security.password_min_length' => '10', 'security.login_max_attempts' => '5', 'security.audit_retention_days' => '365',
      'cron.web_token' => Crypto::token(24), 'cron.web_enabled' => '1', 'email.driver' => 'mail', 'email.from_name' => $d['app_name'], 'storage.max_upload_mb' => '10',
      'crm.invoice_prefix' => 'INV-', 'crm.quotation_prefix' => 'QT-', 'crm.default_tax_rate' => '18', 'hr.work_hours_per_day' => '8', 'attendance.idle_minutes' => '5', 'attendance.screenshots_enabled' => '0', 'attendance.screenshot_interval' => '3', 'attendance.screenshot_retention_days' => '30',
      'ai.enabled' => '0', 'ai.provider' => 'anthropic', 'ai.monthly_token_budget' => '500000', 'ai.user_daily_requests' => '50', 'ai.redact_pii' => '1', 'backups.enabled' => '1', 'backups.time' => '02:30', 'backups.keep' => '7', 'updates.channel' => 'release', 'updates.repo' => '']);
    $roleId = (int) DB::value("SELECT id FROM roles WHERE slug='super_admin'");
    return DB::insert('users', ['role_id' => $roleId, 'name' => $d['name'], 'email' => strtolower($d['email']), 'password_hash' => password_hash((string) $d['password'], PASSWORD_DEFAULT), 'status' => 'active', 'joined_on' => date('Y-m-d'), 'created_at' => $now, 'updated_at' => $now]); } }
